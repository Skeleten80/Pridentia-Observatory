def seed(db: ObjectDatabase, rebuild: bool = False) -> None:
    """Populate the database.  If rebuild=True, clears all existing rows first."""
    if rebuild:
        db.clear_all()

    existing = db.count()
    if existing > 0 and not rebuild:
        print(f"Database already has {existing} objects. Use --rebuild to re-seed.")
        return

    all_data = SOLAR_SYSTEM + MESSIER + BRIGHT_STARS + NOTABLE_NGC_IC

    inserted = 0
    for entry in all_data:
        obj = CelestialObject(
            name=entry["name"],
            catalogue_ids=entry.get("catalogue_ids", []),
            common_names=entry.get("common_names", []),
            object_type=entry["object_type"],
            ra_hours=entry["ra_hours"],
            dec_degrees=entry["dec_degrees"],
            magnitude=entry.get("magnitude"),
            angular_size_arcmin=entry.get("angular_size_arcmin"),
            constellation=entry.get("constellation", ""),
            description=entry.get("description", ""),
        )
        db.insert_object(obj)
        inserted += 1

    print(f"Seeded {inserted} objects into the Prudentia Observatory catalogue.")


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    parser = argparse.ArgumentParser(description="Seed Prudentia Observatory catalogues.")
    parser.add_argument("--rebuild", action="store_true", help="Clear and re-seed the database.")
    args = parser.parse_args()
    from prudentia_observatory.app.core.object_database import ObjectDatabase
    db = ObjectDatabase()
    seed(db, rebuild=args.rebuild)
